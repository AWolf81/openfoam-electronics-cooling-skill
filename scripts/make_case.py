#!/usr/bin/env python3
"""Write a complete OpenFOAM v2412 (ESI) conjugate-heat-transfer case from a case YAML.

    python3 make_case.py case.yaml OUT_DIR [--resolution coarse|normal|fine] [--force]

What it builds (geometry convention in cooling_model.py):
  * one structured blockMesh whose grid lines fall exactly on every solid edge
    (fins, base, board spreader, packages), so topoSet boxes select cells without staircasing;
  * cellZones -> splitMeshRegions -> regions: air (fluid), heatsink, ims, one per device;
  * laminar buoyant air, open boundaries on all sides; with airflow.mode forced one of them
    is a uniform fan inlet (along the fins, or onto the component side)
    (or a wall behind the sink when heatsink.back = wall);
  * fvDOM surface radiation in the air (transparent air, grey diffuse surfaces);
  * the board (region "ims") meshed as its spreader plate (Al of an IMS, Cu core, ...);
    the layers from each part down to it and from it down to the sink as thin thermal
    layers on those interfaces (board.layers_under_parts / board.layers_to_sink);
  * device losses as absolute volumetric heat sources, power from the hand-calc
    fixed point (Rds(on) at the predicted Tj) unless power_W is given;
  * function objects for the energy balance, radiation share, case temperatures.

The case runs with scripts/of.sh OUT_DIR ./Allrun. Nothing here talks to the network.
"""

