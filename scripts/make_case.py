RES = {  # cells across a fin gap, cells along fin height, cells along sink length, far-field growth cap
    "coarse": {"gap": 4, "fin_h": 6, "len": 30, "grow": 1.25},
    "normal": {"gap": 6, "fin_h": 10, "len": 50, "grow": 1.15},
    "fine":   {"gap": 9, "fin_h": 15, "len": 75, "grow": 1.10},
}


def foam(path: Path, obj: str, body: str, cls: str = "dictionary", loc: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    loc_line = f'location    "{loc}";\n    ' if loc else ""
    path.write_text(HEADER.format(cls=cls, obj=obj, loc=loc_line) + body.strip() + "\n\n"
                    "// ************************************************************************* //\n")


