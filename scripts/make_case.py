def write_mesh(case: Path, cfg: Config, grid, boxes) -> None:
    (x0, x1), (y0, y1), (z0, z1) = [(grid[a][0][0], grid[a][0][-1]) for a in "xyz"]
    n = [sum(c for _, c, _ in grid[a][1]) for a in "xyz"]

    def grading(axis):
        segs = grid[axis][1]
        Lt = sum(s[0] for s in segs)
        Nt = sum(s[1] for s in segs)
        return "(" + " ".join(f"({s[0] / Lt:.10g} {s[1] / Nt:.10g} {s[2]:.6g})" for s in segs) + ")"

    back_type = "wall" if cfg.sink["back"] == "wall" else "patch"
    foam(case / "system/blockMeshDict", "blockMeshDict", f"""
scale   1;

vertices
(
    ({x0:.9g} {y0:.9g} {z0:.9g})
    ({x1:.9g} {y0:.9g} {z0:.9g})
    ({x1:.9g} {y1:.9g} {z0:.9g})
    ({x0:.9g} {y1:.9g} {z0:.9g})
    ({x0:.9g} {y0:.9g} {z1:.9g})
    ({x1:.9g} {y0:.9g} {z1:.9g})
    ({x1:.9g} {y1:.9g} {z1:.9g})
    ({x0:.9g} {y1:.9g} {z1:.9g})
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({n[0]} {n[1]} {n[2]})
    simpleGrading
    (
        {grading("x")}
        {grading("y")}
        {grading("z")}
    )
);

boundary
(
    back   {{ type {back_type}; faces ((0 4 7 3)); }}
    front  {{ type patch; faces ((1 2 6 5)); }}
    left   {{ type patch; faces ((0 1 5 4)); }}
    right  {{ type patch; faces ((3 7 6 2)); }}
    bottom {{ type patch; faces ((0 3 2 1)); }}
    top    {{ type patch; faces ((4 5 6 7)); }}
);
""")

    actions = []
    eps = 1e-7
    isl = island_names(cfg)
    for name, bxs in boxes.items():
        for i, ((a, b), (c, d), (e, f)) in enumerate(bxs):
            actions.append(f"""    {{
        name    {name}Set;
        type    cellSet;
        action  {"new" if i == 0 else "add"};
        source  boxToCell;
        box     ({a - eps:.9g} {c - eps:.9g} {e - eps:.9g}) ({b + eps:.9g} {d + eps:.9g} {f + eps:.9g});
    }}""")
        if name == "ims":   # islands are cut out of the board; shrink boxes so shared faces stay with ims
            for n in isl:
                for (a, b), (c, d), (e, f) in boxes[n]:
                    actions.append(f"""    {{
        name    imsSet;
        type    cellSet;
        action  subtract;
        source  boxToCell;
        box     ({a + eps:.9g} {c + eps:.9g} {e + eps:.9g}) ({b - eps:.9g} {d - eps:.9g} {f - eps:.9g});
    }}""")
        actions.append(f"""    {{
        name    {name};
        type    cellZoneSet;
        action  new;
        source  setToCellZone;
        set     {name}Set;
    }}""")
    # air = everything that is not solid
    first = True
    for name in boxes:
        actions.append(f"""    {{
        name    airSet;
        type    cellSet;
        action  {"new" if first else "add"};
        source  cellToCell;
        set     {name}Set;
    }}""")
        first = False
    actions.append("""    {
        name    airSet;
        type    cellSet;
        action  invert;
    }
    {
        name    air;
        type    cellZoneSet;
        action  new;
        source  setToCellZone;
        set     airSet;
    }""")
    foam(case / "system/topoSetDict", "topoSetDict", "actions\n(\n" + "\n".join(actions) + "\n);")


