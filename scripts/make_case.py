def solids(cfg: Config) -> dict:
    """Region name -> list of boxes ((x0,x1),(y0,y1),(z0,z1)) in m."""
    s, im = cfg.sink, cfg.ims
    W, L, b, H, t, n, gap = (s["width"], s["length"], s["base"], s["fin_h"],
                             s["fin_t"], s["n_fins"], s["gap"])
    hs = [((0.0, b), (0.0, W), (0.0, L))]
    for i in range(n):
        y0 = i * (t + gap)
        hs.append(((b, b + H), (y0, y0 + t), (0.0, L)))
    cy, cz = im["centre"]
    sy, sz = im["size"]
    out = {"heatsink": hs,
           "ims": [((-im["substrate"], 0.0), (cy - sy / 2, cy + sy / 2), (cz - sz / 2, cz + sz / 2))]}
    for d in cfg.devices:
        dy, dz = d.centre
        wy, wz, th = d.size
        x1 = -im["substrate"]
        out[d.name] = [((x1 - th, x1), (dy - wy / 2, dy + wy / 2), (dz - wz / 2, dz + wz / 2))]
    # Islands of a patterned spreader: same level as the spreader; region 'ims' keeps the rest
    # (topoSet subtracts the islands from it).
    for isl in im.get("islands", []):
        out[isl["name"]] = [((-im["substrate"], 0.0), (y0, y1), (z0, z1)) for y0, y1, z0, z1 in isl["boxes"]]
    # Extra parts (cfg.solids): height above the board's top surface; +-inf in y or z runs to
    # the domain boundary (a cable leaving the model).
    clr = clearances(cfg)
    ylim, zlim = (-clr["sides"], W + clr["sides"]), (-clr["below"], L + clr["above"])
    clip = lambda v, lim: min(max(v, lim[0]), lim[1])  # noqa: E731
    for p in cfg.solids:
        out[p["name"]] = [((-im["substrate"] - b["h"][1], -im["substrate"] - b["h"][0]),
                           tuple(sorted(clip(v, ylim) for v in b["y"])),
                           tuple(sorted(clip(v, zlim) for v in b["z"]))) for b in p["boxes"]]
    _check_overlap(out, inside={i["name"] for i in im.get("islands", [])})
    return out


def island_names(cfg: Config) -> list:
    return [i["name"] for i in cfg.ims.get("islands", [])]


def clearances(cfg: Config) -> dict:
    """Air around the assembly to the domain boundary, m."""
    clr = {"front": 120, "back": 40, "sides": 60, "below": 60, "above": 300}
    clr.update(cfg.mesh.get("clearance_mm", {}))
    return {k: v * MM for k, v in clr.items()}


def _check_overlap(boxes: dict, inside: set = frozenset()) -> None:
    """No two regions may share volume; islands lie inside the 'ims' box by design."""
    items = [(n, b) for n, bs in boxes.items() for b in bs]
    for i, (n1, a) in enumerate(items):
        for n2, b in items[i + 1:]:
            if n1 == n2 or {n1, n2} & inside and {n1, n2} & {"ims"}:
                continue
            if all(min(a[k][1], b[k][1]) - max(a[k][0], b[k][0]) > 1e-9 for k in range(3)):
                raise ValueError(f"solids {n1} and {n2} overlap")


def _merge(points, tol):
    pts = sorted(points)
    out = [pts[0]]
    for p in pts[1:]:
        if p - out[-1] > tol:
            out.append(p)
    return out


def _far(length, d_near, grow, d_cap):
    """Cells and expansion ratio (last/first, growing away from the sink) for a far-field span."""
    n, total, d = 0, 0.0, d_near
    while total < length:
        total += d
        n += 1
        d = min(d * grow, d_cap)
    n = max(n, 1)
    # first-to-last ratio of a geometric series matching that n and length
    lo, hi = 1.0, 1e3
    for _ in range(100):
        r = (lo + hi) / 2
        q = r ** (1 / max(n - 1, 1))
        L = d_near * (q ** n - 1) / (q - 1) if q > 1 + 1e-12 else d_near * n
        if L > length:
            hi = r
        else:
            lo = r
    return n, r


def axis_segments(breaks, near_lo, near_hi, d_near, grow, d_cap, n_min):
    """Segments (length, cells, expansion) along one axis. Inside [near_lo, near_hi] cells are
    uniform at ~d_near (at least n_min per segment); outside they grow away from the sink."""
    segs = []
    for a, c in zip(breaks[:-1], breaks[1:]):
        ln = c - a
        if a >= near_lo - 1e-12 and c <= near_hi + 1e-12:
            segs.append((ln, max(n_min, math.ceil(ln / d_near - 1e-9)), 1.0))
        else:
            n, r = _far(ln, d_near, grow, d_cap)
            segs.append((ln, n, r if a >= near_hi - 1e-12 else 1.0 / r))
    return segs


def build_grid(cfg: Config, res: str):
    s = cfg.sink
    R = RES[res]
    clr = clearances(cfg)
    boxes = solids(cfg)
    x_back = min(bx[0][0] for v in boxes.values() for bx in v)
    x_front = s["base"] + s["fin_h"]
    xs = [x_back - clr["back"], x_front + clr["front"]]
    ys = [-clr["sides"], s["width"] + clr["sides"]]
    zs = [-clr["below"], s["length"] + clr["above"]]
    for v in boxes.values():
        for (x0, x1), (y0, y1), (z0, z1) in v:
            xs += [x0, x1]
            ys += [y0, y1]
            zs += [z0, z1]
    tol = 0.2 * MM
    xs, ys, zs = _merge(xs, tol), _merge(ys, tol), _merge(zs, tol)

    dy = min(s["gap"] / R["gap"], s["fin_t"] / 2)
    dx = s["fin_h"] / R["fin_h"]
    dz = s["length"] / R["len"]
    cap = 6 * max(dx, dy, dz)
    gx = axis_segments(xs, x_back, x_front, dx, R["grow"], cap, 2)
    gy = axis_segments(ys, 0.0, s["width"], dy, R["grow"], cap, 2)
    gz = axis_segments(zs, 0.0, s["length"], dz, R["grow"], cap, 2)
    return {"x": (xs, gx), "y": (ys, gy), "z": (zs, gz)}, boxes


def snap_boxes(boxes, grid):
    """Move box faces onto the merged grid breakpoints they were merged into."""
    def snap(v, pts):
        return min(pts, key=lambda p: abs(p - v))
    xs, ys, zs = grid["x"][0], grid["y"][0], grid["z"][0]
    return {k: [((snap(a, xs), snap(b, xs)), (snap(c, ys), snap(d, ys)), (snap(e, zs), snap(f, zs)))
                for (a, b), (c, d), (e, f) in v] for k, v in boxes.items()}


def expected_cells(boxes, grid, islands=()):
    """Cell count per region straight from the grid, to check splitMeshRegions against.
    Islands are cut out of the 'ims' box."""
    def cells_between(axis, lo, hi):
        pts, segs = grid[axis]
        return sum(n for (a, b), (_, n, _) in zip(zip(pts[:-1], pts[1:]), segs)
                   if a >= lo - 1e-12 and b <= hi + 1e-12)
    out = {}
    for k, v in boxes.items():
        out[k] = sum(cells_between("x", *bx[0]) * cells_between("y", *bx[1]) * cells_between("z", *bx[2])
                     for bx in v)
    if islands and "ims" in out:
        out["ims"] -= sum(out[i] for i in islands)
    total = math.prod(sum(n for _, n, _ in grid[a][1]) for a in "xyz")
    out["air"] = total - sum(out.values())
    out["_total"] = total
    return out


